"""Write object-tree version headers without touching unchanged output."""

from functools import lru_cache
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


@lru_cache(maxsize=1)
def commit_id():
    requested = os.environ.get("ROMAW_BUILD_COMMIT", "HEAD")
    if requested != "HEAD" and not re.fullmatch(r"[0-9a-f]{7,40}", requested):
        raise RuntimeError("ROMAW_BUILD_COMMIT must identify a Git commit")
    revision = subprocess.check_output(
        ["git", "-C", str(ROOT), "rev-parse", "--short=12", requested], text=True
    ).strip()
    if not re.fullmatch(r"[0-9a-f]{12,40}", revision):
        raise RuntimeError("The ROMAW build requires a checked-out Git commit")
    return revision


def version_string():
    return "ROMAW version " + commit_id()


def write_header(path):
    path = Path(path)
    value = json.dumps(version_string())
    contents = (
        "/* Generated by tools/build_version.py; do not edit. */\n"
        "#ifndef ROMAW_GENERATED_BUILD_VERSION_H\n#define ROMAW_GENERATED_BUILD_VERSION_H\n"
        f"#define ROMAW_GIT_COMMIT {json.dumps(commit_id())}\n"
        f"#define ROMAW_VERSION {value}\n#define ROMAW_VERSION_W L{value}\n#endif\n"
    ).encode("utf-8")
    if path.is_file() and path.read_bytes() == contents:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(contents)
    temporary.replace(path)


def main():
    if len(sys.argv) == 1:
        print(version_string())
    elif len(sys.argv) == 2:
        write_header(sys.argv[1])
    else:
        raise SystemExit("Usage: build_version.py [output-header]")


if __name__ == "__main__":
    main()
