"""Generate deterministic Unicode lowercase mappings for DSDB key ordering."""

from pathlib import Path
import argparse
import unicodedata

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("output", type=Path)
path = parser.parse_args().output
path.parent.mkdir(parents=True, exist_ok=True)
temporary = path.with_suffix(".tmp")
with temporary.open("w", encoding="utf-8", newline="\n") as output:
    output.write(f"/* Generated by tools/generate-dsstore-case.py; Unicode {unicodedata.unidata_version}. */\n")
    for code in range(0x110000):
        text = chr(code)
        if text.lower() != text:
            value = ", ".join(f"0x{ord(c):x}" for c in text.lower())
            output.write(f"{{ 0x{code:x}, {{ {value} }} }},\n")
temporary.replace(path)
