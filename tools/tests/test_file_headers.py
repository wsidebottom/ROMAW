"""Regression checks for header placement, source preservation and API discovery."""

from pathlib import Path
import subprocess
import sys
import unittest
from unittest.mock import patch
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import file_headers as headers


class FileHeadersTest(unittest.TestCase):
    def add(self, name, source):
        style = headers.style_for(name, source)
        result = headers.add_header(name, source, style)
        self.assertTrue(headers.validate_header(name, result, style))
        self.assertEqual(headers.without_header(result, style), source)
        self.assertEqual(headers.add_header(name, result, style), result)
        return result

    def test_visual_studio_resource_outputs_are_generator_owned(self):
        for name, marker in (
            ("platform/os/cygwin32/resource.h", b"// Microsoft Visual C++ generated include file."),
            ("platform/os/cygwin32/preferences.rc", b"// Microsoft Visual C++ generated resource script."),
        ):
            source = marker + b"\r\n#define IDOK            1\r\n"
            self.assertTrue(headers.is_generated_artifact(source))
            self.assertIsNone(headers.style_for(name, source))
        maintained = self.add("system/example.c", b"int example(void) { return 0; }\n")
        maintained += b"// Microsoft Visual C++ generated include file.\n"
        self.assertFalse(headers.is_generated_artifact(maintained))
        self.assertIsNotNone(headers.style_for("system/example.c", maintained))

    def test_c_notice_and_body_are_byte_identical(self):
        source = b"/* Copyright 1994 Example. All rights reserved. */\nint exported(void) { return 7; }\n"
        result = self.add("system/tests/example.c", source)
        self.assertIn(b"Functions: exported", result)
        self.assertIn(source, result)

    def test_c_trap_macros_have_real_names_and_visibility(self):
        source = b"A0(PUBLIC, int, direct) { return 1; }\nP1(PUBLIC, int, Trap, int, x) { return x; }\nA0(PRIVATE, int, hidden) { return 2; }\nstatic int local(void) { return 3; }\n"
        self.assertEqual(headers.c_symbols(source, "c")["functions"], ["C_Trap", "direct"])

    def test_cpp_namespaces_and_anonymous_helpers(self):
        source = b"namespace visible { int exported() { return 1; } }\nnamespace { int helper() { return 2; } }\n"
        self.assertEqual(headers.c_symbols(source, "cpp")["functions"], ["visible::exported"])

    def test_python_encoding_shebang_and_docstring(self):
        source = b'#!/usr/bin/env python3\n# coding: latin-1\n"""Example module."""\nlabel = "\xe9"\n'
        result = self.add("tools/example.py", source)
        self.assertTrue(result.startswith(b"#!/usr/bin/env python3\n# coding: latin-1\n# +"))
        namespace = {}
        exec(result, namespace)
        self.assertEqual(namespace["__doc__"], "Example module.")
        self.assertEqual(namespace["label"], "\u00e9")

    def test_shell_shebang_and_syntax(self):
        source = b"#!/bin/sh\nset -eu\nvalue=example\n"
        result = self.add("tools/example.sh", source)
        self.assertTrue(result.startswith(b"#!/bin/sh\n# +"))
        subprocess.run(["bash", "-n"], input=result, check=True)

    def test_option_spelling_survives_comment_rendering(self):
        source = b'"""Run --check without writing files."""\n'
        result = self.add("tools/example.py", source)
        self.assertIn(b"Summary:   Run --check without writing files.", result)

    def test_xml_declaration_remains_first(self):
        source = b'<?xml version="1.0" encoding="UTF-8"?>\n<assembly/>\n'
        result = self.add("system/example.manifest", source)
        from xml.etree import ElementTree

        self.assertEqual(ElementTree.fromstring(result).tag, "assembly")

    def test_bom_is_preserved(self):
        source = b"\xef\xbb\xbfint exported(void) { return 1; }\n"
        self.assertTrue(self.add("system/example.c", source).startswith(b"\xef\xbb\xbf/*+"))

    def test_generated_vendored_reference_and_binary_files_are_excluded(self):
        for name, data in [
            ("references/finder7/example.c", b"int x;\n"),
            ("finder7/example.c", b"int x;\n"),
            ("synppc/third_party/example.c", b"int x;\n"),
            ("system/obj/example.c", b"int x;\n"),
            ("system/generated.c", b"/* Generated by a tool. */\nint x;\n"),
            ("system/binary.c", b"\x00data"),
            ("system/../references/example.py", b"pass\n"),
            ("tools/.example.py.123.header-tmp", b"#!/usr/bin/env python3\npass\n"),
        ]:
            with self.subTest(name=name):
                self.assertIsNone(headers.style_for(name, data))

    def test_specialized_languages_keep_native_comment_syntax(self):
        cases = [
            ("system/example.ac", b"AC_INIT([example], [1])\n", b"dnl +"),
            ("syn68k/example.scm", b"(define (example) 1)\n", b"; +"),
            ("system/example.rawdef", b"ReadFile@20\n", b"; +"),
            ("system/Makefile", b"all:\n\ttrue\n", b"# +"),
            ("system/example.y", b"%%\nstart: ;\n%%\n", b"/*+"),
        ]
        for name, data, opening in cases:
            with self.subTest(name=name):
                self.assertTrue(self.add(name, data).startswith(opening))

    def test_renamed_header_is_rejected_until_refreshed(self):
        source = b"int exported(void) { return 1; }\n"
        result = self.add("system/old.c", source)
        style = headers.style_for("system/new.c", result)
        self.assertFalse(headers.validate_header("system/new.c", result, style))
        with self.assertRaises(ValueError):
            headers.add_header("system/new.c", result, style)
        refreshed = headers.add_header("system/new.c", result, style, refresh=True)
        self.assertTrue(headers.validate_header("system/new.c", refreshed, style))

    def test_concurrent_edit_is_preserved_and_metadata_is_recomputed(self):
        name = "system/example.c"
        old = b"int before(void) { return 1; }\n"
        latest = b"int after(void) { return 2; }\n"
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / name
            path.parent.mkdir()
            path.write_bytes(latest)
            style = headers.style_for(name, old)
            with (
                patch.object(headers, "ROOT", root),
                patch.object(headers, "candidates", return_value=[(name, old, style)]),
            ):
                headers.maintain_headers()
            result = path.read_bytes()
            self.assertEqual(headers.without_header(result, style), latest)
            self.assertIn(b"Functions: after", result)

    def test_maintained_script_uses_lf_line_endings(self):
        name = "tools/example.sh"
        source = b"#!/bin/sh\r\nset -eu\r\nvalue=example\r\n"
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / name
            path.parent.mkdir()
            path.write_bytes(source)
            style = headers.style_for(name, source)
            with (
                patch.object(headers, "ROOT", root),
                patch.object(headers, "candidates", return_value=[(name, source, style)]),
            ):
                headers.maintain_headers()
            result = path.read_bytes()
            self.assertNotIn(b"\r\n", result)
            self.assertEqual(headers.without_header(result, style), source.replace(b"\r\n", b"\n"))
            subprocess.run(["bash", "-n"], input=result, check=True)

    def test_refresh_keeps_explicit_origin(self):
        name = "system/example.c"
        source = b"int exported(void) { return 1; }\n"
        style = headers.style_for(name, source)
        fields = headers.metadata(name, source, style)
        fields["Origin"] = "Adapted from the explicitly attributed upstream implementation."
        original = headers.render_header(fields, style) + source
        refreshed = headers.add_header(name, original, style, refresh=True)
        self.assertIn(fields["Origin"].encode(), refreshed)

    def test_embedded_legal_notice_requires_manual_refresh(self):
        name = "system/example.c"
        source = b"int exported(void) { return 1; }\n"
        style = headers.style_for(name, source)
        fields = headers.metadata(name, source, style)
        fields["Copyright and Legal notices"] = "Copyright (c) 2026 Example Owner. All rights reserved."
        original = headers.render_header(fields, style) + source
        self.assertTrue(headers.validate_header(name, original, style))
        self.assertEqual(headers.add_header(name, original, style), original)
        unlabeled = original.replace(b"Copyright and Legal notices: ", b"")
        self.assertTrue(headers.validate_header(name, unlabeled, style))
        self.assertEqual(headers.add_header(name, unlabeled, style), unlabeled)
        with self.assertRaises(ValueError):
            headers.add_header(name, original, style, refresh=True)


if __name__ == "__main__":
    unittest.main()
