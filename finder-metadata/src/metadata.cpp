extern "C" int finder_window_read(const char* folder, FinderWindowState* state, char* error, size_t capacity)
{
    std::lock_guard<std::mutex> lock(metadata_mutex);
    try {
        auto p = folder_path(folder);
        bool root = p == p.root_path();
        Store s;
        s.load(presentation_path(root ? p : p.parent_path(), false, p));
        auto r = s.find(root ? std::u16string(1, '.') : utf16(p.filename().u8string()), 0x66776930);
        if (!r)
            return 0;
        need(r->type == 0x626c6f62 && r->value.size() == 20 && u32(r->value, 0) == 16);
        auto& b = r->value;
        auto short_at = [&](size_t i) { return int(int16_t((b[i] << 8) | b[i + 1])); };
        state->y = short_at(4);
        state->x = short_at(6);
        state->height = short_at(8) - state->y;
        state->width = short_at(10) - state->x;
        auto view = u32(b, 12);
        auto name = root ? std::u16string(1, '.') : utf16(p.filename().u8string());
        if (auto v = s.find(name, 0x7673746c))
            if (v->type == 0x74797065 && v->value.size() == 4)
                view = u32(v->value, 0);
        if (auto h = s.find(name, 0x66777668))
            if (h->type == 0x73686f72 && h->value.size() == 4) {
                auto value = u32(h->value, 0);
                need(value <= 65535);
                state->height = value;
            }
        state->view = view == 0x4e6c7376 ? 2 : view == 0x636c6d76 ? 1 : 0;
        // ROMAW's list variant is an extension record; the standard view
        // remains Nlsv, which Finder on classic OS X understands.
        if (state->view == 2)
            if (auto variant = s.find(name, 0x65467677)) // eFvw
                if (variant->type == 0x6c6f6e67 && variant->value.size() == 4 && u32(variant->value, 0) == 3)
                    state->view = 3;
        if (view == 0x69636e76)
            if (auto icon = s.find(name, 0x6963766f))
                if (icon->type == 0x626c6f62 && icon->value.size() == 22 && u32(icon->value, 0) == 18 &&
                    u32(icon->value, 4) == 0x6963766f)
                    state->view = ((icon->value[16] << 8) | icon->value[17]) <= 16 ? 1 : 0;
        need(state->width >= 100 && state->height >= 80);
        return 1;
    }
    catch (const std::exception& e) {
        return failure(error, capacity, e);
    }
}

extern "C" int finder_window_write(const char* folder, const FinderWindowState* state, char* error, size_t capacity)
{
    if (finder_image_contains(folder))
        return failure(error, capacity, std::runtime_error("Mounted images are read-only"));
    std::lock_guard<std::mutex> lock(metadata_mutex);
    try {
        need(state->width >= 100 && state->height >= 80);
        auto p = folder_path(folder);
        bool root = p == p.root_path();
        auto path = presentation_path(root ? p : p.parent_path(), true, p);
        Store s;
        s.load(path);
        Bytes rect;
        for (int64_t n : {int64_t(state->y), int64_t(state->x), int64_t(state->y) + state->height,
                          int64_t(state->x) + state->width}) {
            need(n >= -32768 && n <= 32767);
            rect.push_back(n >> 8);
            rect.push_back(n);
        }
        put(rect, state->view >= 2 ? 0x4e6c7376 : 0x69636e76);
        put(rect, 0);
        auto name = root ? std::u16string(1, '.') : utf16(p.filename().u8string());
        s.set(blob(name, 0x66776930, rect));
        Bytes height;
        put(height, state->height);
        s.set({name, 0x66777668, 0x73686f72, height});
        Bytes view;
        put(view, state->view >= 2 ? 0x4e6c7376 : 0x69636e76);
        s.set({name, 0x7673746c, 0x74797065, view});
        Bytes variant;
        put(variant, state->view);
        s.set({name, 0x65467677, 0x6c6f6e67, variant});
        // Small icons are icon view with a 16-point icvo size. clmv denotes
        // macOS column view, not classic small icons. Preserve existing flags.
        if (state->view < 2) {
            auto previous = s.find(name, 0x6963766f);
            if (!previous || (previous->type == 0x626c6f62 && previous->value.size() == 22 &&
                              u32(previous->value, 0) == 18 && u32(previous->value, 4) == 0x6963766f)) {
                Bytes options(18);
                patch(options, 0, 0x6963766f);
                patch(options, 14, 0x6e6f6e65);
                if (previous)
                    std::copy(previous->value.begin() + 4, previous->value.end(), options.begin());
                options[12] = 0;
                options[13] = state->view == 1 ? 16 : 32;
                s.set(blob(name, 0x6963766f, options));
            }
        }
        save(s, path);
        return 1;
    }
    catch (const std::exception& e) {
        return failure(error, capacity, e);
    }
}

extern "C" int finder_icon_position(const char* folder, const char* name, int* x, int* y, int write, char* error,
                                    size_t capacity)
{
    if (write && finder_image_contains(folder))
        return failure(error, capacity, std::runtime_error("Mounted images are read-only"));
    std::lock_guard<std::mutex> lock(metadata_mutex);
    try {
        auto p = store_path(folder, write != 0);
        Store s;
        s.load(p);
        auto n = utf16(name);
        if (write) {
            need(*x >= 0 && *y >= 0);
            Bytes value;
            put(value, *x);
            put(value, *y);
            put(value, 0xffffffff);
            put(value, 0xffff0000);
            s.set(blob(n, 0x496c6f63, value));
            save(s, p);
            return 1;
        }
        auto r = s.find(n, 0x496c6f63);
        if (!r)
            return 0;
        need(r->type == 0x626c6f62 && r->value.size() >= 12);
        auto a = u32(r->value, 4), b = u32(r->value, 8);
        need(a <= 0x7fffffff && b <= 0x7fffffff);
        *x = a;
        *y = b;
        return 1;
    }
    catch (const std::exception& e) {
        return failure(error, capacity, e);
    }
}

extern "C" int finder_metadata_rename(const char* folder, const char* old_name, const char* new_name, char* error,
                                      size_t capacity)
{
    std::lock_guard<std::mutex> lock(metadata_mutex);
    try {
        auto p = store_path(folder, true);
        Store s;
        s.load(p);
        auto old = utf16(old_name), name = utf16(new_name);
        std::vector<Record> moved;
        for (auto i = s.records.begin(); i != s.records.end();)
            if (lower(i->name) == lower(old)) {
                Record record = *i;
                record.name = name;
                moved.push_back(std::move(record));
                i = s.records.erase(i);
            }
            else
                ++i;
        if (!moved.empty()) {
            // A deleted destination can have stale presentation records. The
            // renamed item's matching keys take precedence over those records.
            for (auto& record : moved)
                s.set(std::move(record));
            save(s, p);
        }
        return 1;
    }
    catch (const std::exception& e) {
        return failure(error, capacity, e);
    }
}

extern "C" int finder_native_session_write(const char* const* paths, const FinderWindowState* states, size_t count)
{
    char file[32768];
    if (!romaw_profile_path("ROMAW.prefs", file, sizeof file, nullptr, 0))
        return 0;
    FILE* script = tmpfile();
    if (!script)
        return 0;
    size_t saved_count = 0;
    for (size_t i = 0; i < count; ++i) {
        if (finder_image_contains(paths[i]))
            continue;
        std::ostringstream value;
        std::string encoded;
        for (const unsigned char* p = (const unsigned char*)paths[i]; *p; ++p)
            if (*p < 32 || *p == '%' || *p == 127) {
                char code[4];
                snprintf(code, sizeof code, "%%%02X", *p);
                encoded += code;
            }
            else
                encoded += char(*p);
        value << std::quoted(encoded);
        ++saved_count;
        fprintf(script, "Window%zu=%s\n", saved_count, value.str().c_str());
        if (states)
            fprintf(script, "Bounds%zu=%d,%d,%d,%d,%d\n", saved_count, states[i].x, states[i].y, states[i].width,
                    states[i].height, states[i].view);
    }
    int ok = config_prefs_store_ini(file, "Finder.OpenWindows", script);
    fclose(script);
    return ok;
}

extern "C" int finder_native_session_read(FinderSessionVisitor visitor, void* context)
{
    char file[32768];
    if (!romaw_profile_path("ROMAW.prefs", file, sizeof file, nullptr, 0))
        return 0;
    for (size_t i = 1;; ++i) {
        char key[64], value[32768];
        snprintf(key, sizeof key, "Window%zu", i);
        if (!config_prefs_get(file, "Finder.OpenWindows", key, value, sizeof value))
            break;
        std::istringstream in(value);
        std::string path;
        if (!(in >> std::quoted(path)))
            return 0;
        std::string decoded;
        for (size_t n = 0; n < path.size(); ++n) {
            if (path[n] == '%') {
                if (n + 2 >= path.size())
                    return 0;
                auto digit = [](char c) {
                    return c >= '0' && c <= '9' ? c - '0' : c >= 'A' && c <= 'F' ? c - 'A' + 10 : -1;
                };
                int a = digit(path[n + 1]), b = digit(path[n + 2]);
                if (a < 0 || b < 0 || !(a * 16 + b))
                    return 0;
                decoded += char(a * 16 + b);
                n += 2;
            }
            else
                decoded += path[n];
        }
        if (!visitor(decoded.c_str(), context))
            return 0;
    }
    return 1;
}

extern "C" int finder_native_session_window(const char* path, FinderWindowState* state)
{
    char file[32768];
    if (!romaw_profile_path("ROMAW.prefs", file, sizeof file, nullptr, 0))
        return 0;

    struct Match {
        const char* path;
        size_t index = 0, current = 0;
    };

    Match match{path};
    finder_native_session_read(
        [](const char* candidate, void* context) {
            auto* m = (Match*)context;
            ++m->current;
            if (!strcmp(candidate, m->path)) {
                m->index = m->current;
                return 0;
            }
            return 1;
        },
        &match);
    if (!match.index)
        return 0;
    char key[64], value[256];
    snprintf(key, sizeof key, "Bounds%zu", match.index);
    if (!config_prefs_get(file, "Finder.OpenWindows", key, value, sizeof value))
        return 0;
    const char *position = value, *end = value + strlen(value);
    int fields[5];
    for (int i = 0; i < 5; ++i) {
        auto parsed = std::from_chars(position, end, fields[i]);
        if (parsed.ec != std::errc())
            return 0;
        position = parsed.ptr;
        if (i < 4) {
            if (position == end || *position++ != ',')
                return 0;
        }
    }
    if (position != end)
        return 0;
    *state = {fields[0], fields[1], fields[2], fields[3], fields[4]};
    return state->x >= -32768 && state->x <= 32767 && state->y >= -32768 && state->y <= 32767 && state->width >= 100 &&
           state->width <= 32767 && state->height >= 80 && state->height <= 32767 && state->view >= 0 &&
           state->view <= 3;
}

namespace {
int layout(const char* folder, FinderItemPosition* items, size_t count, bool write, char* error, size_t capacity)
{
    if (write && finder_image_contains(folder))
        return failure(error, capacity, std::runtime_error("Mounted images are read-only"));
    std::lock_guard<std::mutex> lock(metadata_mutex);
    try {
        auto path = store_path(folder, write);
        Store s;
        s.load(path);
        for (size_t i = 0; i < count; ++i) {
            auto& item = items[i];
            auto name = utf16(item.name);
            if (write) {
                if (!item.present)
                    continue;
                need(item.x >= 0 && item.y >= 0);
                Bytes b;
                put(b, item.x);
                put(b, item.y);
                put(b, 0xffffffff);
                put(b, 0xffff0000);
                s.set(blob(name, 0x496c6f63, b));
            }
            else {
                item.present = 0;
                auto r = s.find(name, 0x496c6f63);
                if (!r)
                    continue;
                need(r->type == 0x626c6f62 && r->value.size() >= 12);
                auto x = u32(r->value, 4), y = u32(r->value, 8);
                need(x <= 0x7fffffff && y <= 0x7fffffff);
                item.x = x;
                item.y = y;
                item.present = 1;
            }
        }
        if (write)
            save(s, path);
        return 1;
    }
    catch (const std::exception& e) {
        return failure(error, capacity, e);
    }
}

struct MetadataWriter {
    std::mutex mutex;
    std::condition_variable changed;

    struct Update {
        std::string folder;
        FinderWindowState state;
        std::vector<FinderItemPosition> items;
        bool window;
    };

    std::deque<Update> queue;
    bool stop = false, busy = false;
    std::thread thread;

    MetadataWriter()
        : thread([this] {
              std::unique_lock<std::mutex> lock(mutex);
              for (;;) {
                  changed.wait(lock, [this] { return stop || !queue.empty(); });
                  if (queue.empty() && stop)
                      break;
                  auto item = std::move(queue.front());
                  queue.pop_front();
                  busy = true;
                  lock.unlock();
                  char error[512];
                  int result = item.window ? finder_window_write(item.folder.c_str(), &item.state, error, sizeof error)
                                           : layout(item.folder.c_str(), item.items.data(), item.items.size(), true,
                                                    error, sizeof error);
                  if (result < 0)
                      std::fprintf(stderr, "Finder metadata: %s\n", error);
                  lock.lock();
                  busy = false;
                  changed.notify_all();
              }
          })
    {
    }

    ~MetadataWriter()
    {
        {
            std::lock_guard<std::mutex> lock(mutex);
            stop = true;
        }
        changed.notify_all();
        thread.join();
    }
};

MetadataWriter& writer()
{
    static MetadataWriter value;
    return value;
}
}

extern "C" void finder_window_schedule(const char* folder, const FinderWindowState* state)
{
    if (finder_image_contains(folder))
        return;
    auto& w = writer();
    {
        std::lock_guard<std::mutex> lock(w.mutex);
        for (auto& item : w.queue)
            if (item.folder == folder && item.window) {
                item.state = *state;
                return;
            }
        w.queue.push_back({folder, *state, {}, true});
    }
    w.changed.notify_all();
}

extern "C" void finder_metadata_flush(void)
{
    auto& w = writer();
    std::unique_lock<std::mutex> lock(w.mutex);
    w.changed.wait(lock, [&] { return w.queue.empty() && !w.busy; });
}

extern "C" int finder_layout_read(const char* folder, FinderItemPosition* items, size_t count, char* error,
                                  size_t capacity)
{
    return layout(folder, items, count, false, error, capacity);
}

extern "C" int finder_layout_write(const char* folder, FinderItemPosition* items, size_t count, char* error,
                                   size_t capacity)
{
    return layout(folder, items, count, true, error, capacity);
}

extern "C" void finder_layout_schedule(const char* folder, const FinderItemPosition* items, size_t count)
{
    if (finder_image_contains(folder))
        return;
    auto& w = writer();
    std::vector<FinderItemPosition> copy(items, items + count);
    {
        std::lock_guard<std::mutex> lock(w.mutex);
        for (auto& item : w.queue)
            if (item.folder == folder && !item.window) {
                item.items = std::move(copy);
                return;
            }
        w.queue.push_back({folder, {}, std::move(copy), false});
    }
    w.changed.notify_all();
}
