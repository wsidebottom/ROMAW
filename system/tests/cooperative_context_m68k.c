#include <stdint.h>

/* ABI-only trap veneer is generated by the test builder. */
extern uint32_t exchange_context(uint32_t save, uint32_t load);

struct probe {
    uint8_t contexts[3][512];
    volatile uint32_t progress[3];
    volatile uint32_t finished[3];
};

static __attribute__((noinline, noreturn)) void worker(struct probe* probe, uint32_t id)
{
    uint32_t other = id == 1 ? 2 : 1;
    uint32_t checksum = id * 1000;
    for (uint32_t i = 1; i <= 100; ++i) {
        checksum += i;
        probe->progress[id] = i;
        exchange_context((uint32_t)probe->contexts[id], (uint32_t)probe->contexts[other]);
    }
    probe->finished[id] = checksum == id * 1000 + 5050;
    for (;;)
        exchange_context((uint32_t)probe->contexts[id], (uint32_t)probe->contexts[0]);
}

/* Match Finder's ordinary C command-dispatch return frame. The same entry
   recognizes the completion tag when a worker returns, without requiring
   platform assembly in the operation body. */
static __attribute__((noinline)) uint32_t returning_worker(uint32_t first, uint32_t second, uint32_t third)
{
    if (second == 0x46494e49u) {
        struct probe* probe = (struct probe*)third;
        probe->finished[first] = probe->progress[first] == 100;
        for (;;)
            exchange_context(0, (uint32_t)probe->contexts[0]);
    }
    struct probe* probe = (struct probe*)first;
    uint32_t id = second;
    uint32_t other = id == 1 ? 2 : 1;
    for (uint32_t i = 1; i <= 100; ++i) {
        probe->progress[id] = i;
        exchange_context((uint32_t)probe->contexts[id], (uint32_t)probe->contexts[other]);
    }
    return 0;
}

__attribute__((section(".text.probe"))) uint32_t cooperative_probe(void)
{
    struct probe probe;
    uint32_t stacks[2][4096];
    for (uint32_t i = 0; i < sizeof probe; ++i)
        ((volatile uint8_t*)&probe)[i] = 0;
    exchange_context((uint32_t)probe.contexts[1], UINT32_MAX);
    if (*(uint32_t*)(probe.contexts[1] + 8) != 0)
        return 0;
    exchange_context((uint32_t)probe.contexts[0], 0);
    for (uint32_t id = 1; id <= 2; ++id) {
        for (uint32_t i = 0; i < 512; ++i)
            probe.contexts[id][i] = probe.contexts[0][i];
        uint32_t* frame = &stacks[id - 1][4093];
        frame[0] = 0;
        frame[1] = (uint32_t)&probe;
        frame[2] = id;
        *(uint32_t*)(probe.contexts[id] + 8) = (uint32_t)worker;
        *(uint32_t*)(probe.contexts[id] + 76) = (uint32_t)frame;
    }
    while (!probe.finished[1] || !probe.finished[2]) {
        uint32_t next = probe.finished[1] ? 2 : 1;
        exchange_context((uint32_t)probe.contexts[0], (uint32_t)probe.contexts[next]);
    }
    if (probe.progress[1] != 100 || probe.progress[2] != 100)
        return 0;
    for (uint32_t i = 0; i < sizeof probe; ++i)
        ((volatile uint8_t*)&probe)[i] = 0;
    exchange_context((uint32_t)probe.contexts[0], 0);
    for (uint32_t id = 1; id <= 2; ++id) {
        for (uint32_t i = 0; i < 512; ++i)
            probe.contexts[id][i] = probe.contexts[0][i];
        uint32_t* frame = &stacks[id - 1][4091];
        frame[0] = (uint32_t)returning_worker;
        frame[1] = (uint32_t)&probe;
        frame[2] = id;
        frame[3] = 0x46494e49u;
        frame[4] = (uint32_t)&probe;
        *(uint32_t*)(probe.contexts[id] + 8) = (uint32_t)returning_worker;
        *(uint32_t*)(probe.contexts[id] + 76) = (uint32_t)frame;
    }
    while (!probe.finished[1] || !probe.finished[2])
        exchange_context((uint32_t)probe.contexts[0], (uint32_t)probe.contexts[probe.finished[1] ? 2 : 1]);
    return probe.progress[1] == 100 && probe.progress[2] == 100;
}
