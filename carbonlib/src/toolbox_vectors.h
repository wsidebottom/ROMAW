/* The Pascal ProcInfo supplies every parameter width. The bridge narrows these
   guest words when calling a PPC descriptor or pushing the 68K stack. Some
   wrappers additionally narrow the result returned by CallUniversalProc. */
#define TOOLBOX_WRAPPER(name, vector, info, selector, result_type)                           \
    static int carbon_vector_##name(ROMlib_carbon_ppc_frame* call_frame)                     \
    {                                                                                        \
        uint32_t result;                                                                     \
        if (!ROMlib_carbon_call_toolbox_vector(vector, info, selector, call_frame, &result)) \
            return 0;                                                                        \
        call_frame->words[0] = (result_type)result;                                          \
        return 1;                                                                            \
    }

#define TOOLBOX_VECTOR(name, vector, info, result_type) TOOLBOX_WRAPPER(name, vector, info, 0, result_type)
#define TOOLBOX_SELECTOR(name, vector, info, selector, result_type) \
    TOOLBOX_WRAPPER(name, vector, info, selector, result_type)

