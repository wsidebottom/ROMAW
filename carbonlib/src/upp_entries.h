#define CARBON_INVOKE_UPP(name, info, count, result_type)                       \
    static int carbon_##name(ROMlib_carbon_ppc_frame* call_frame)               \
    {                                                                           \
        uint32_t result, procedure;                                             \
        if (!ROMlib_carbon_frame_word(call_frame, count, &procedure) ||         \
            !ROMlib_carbon_invoke_pascal(procedure, info, call_frame, &result)) \
            return 0;                                                           \
        call_frame->words[0] = (result_type)result;                             \
        return 1;                                                               \
    }

