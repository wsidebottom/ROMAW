#define CARBON_MIXED_UPP(name, info, count, result_type, mask)                     \
    static int carbon_##name(ROMlib_carbon_ppc_frame* call_frame)                  \
    {                                                                              \
        const uint32_t procedure = call_frame->words[count];                       \
        uint32_t result;                                                           \
        call_frame->words[0] &= mask;                                              \
        if (!ROMlib_carbon_invoke_mixed_upp(procedure, info, call_frame, &result)) \
            return 0;                                                              \
        call_frame->words[0] = (result_type)result;                                \
        return 1;                                                                  \
    }

